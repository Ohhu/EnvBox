#!/usr/bin/env node
// Generates platform bindings from design/tokens.json.
// Run: node Scripts/gen-design-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

const lines = [];
lines.push("/* AUTO-GENERATED by Scripts/gen-design-tokens.mjs — do not edit. */");
lines.push(":root {");
for (const [name, value] of Object.entries(tokens.color.light)) {
  lines.push(`  --c-${kebab(name)}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.color.brand)) {
  lines.push(`  --brand-${name}: ${value};`);
}
for (const [tint, pair] of Object.entries(tokens.color.tints)) {
  lines.push(`  --tint-${tint}-1: ${pair.primary};`);
  lines.push(`  --tint-${tint}-2: ${pair.secondary};`);
}
for (const [name, value] of Object.entries(tokens.radius)) lines.push(`  --r-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.space)) lines.push(`  --s-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.type)) lines.push(`  --fs-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.size)) lines.push(`  --z-${name}: ${value}px;`);
lines.push(`  --motion-fast: ${tokens.motion.fast};`);
lines.push(`  --motion-snappy: ${tokens.motion.snappy};`);
lines.push(`  --motion-ease: ${tokens.motion.easing};`);
lines.push("}");
lines.push("");
lines.push("@media (prefers-color-scheme: dark) {");
lines.push("  :root {");
for (const [name, value] of Object.entries(tokens.color.dark)) {
  lines.push(`    --c-${kebab(name)}: ${value};`);
}
lines.push("  }");
lines.push("}");
lines.push("");
lines.push("[data-theme='light'] {");
for (const [name, value] of Object.entries(tokens.color.light)) lines.push(`  --c-${kebab(name)}: ${value};`);
lines.push("}");
lines.push("[data-theme='dark'] {");
for (const [name, value] of Object.entries(tokens.color.dark)) lines.push(`  --c-${kebab(name)}: ${value};`);
lines.push("}");

writeFileSync(join(root, "cmd/envbox/web/tokens.css"), lines.join("\n") + "\n");

const swift = [];
swift.push("// AUTO-GENERATED by Scripts/gen-design-tokens.mjs — do not edit.");
swift.push("import CoreGraphics");
swift.push("");
swift.push("enum EnvBoxTokens {");
swift.push("    enum Palette {");
for (const [name, value] of Object.entries(tokens.color.brand)) {
  swift.push(`        static let ${name} = "${value}"`);
}
swift.push("        enum Tint {");
swift.push("            static let aurora = (primary: \"#59EDC7\", secondary: \"#47C2E6\")");
swift.push("            static let ocean = (primary: \"#4F9CFF\", secondary: \"#6E7DFF\")");
swift.push("            static let ember = (primary: \"#FF8F4F\", secondary: \"#FF708F\")");
swift.push("            static let orchid = (primary: \"#C27DFF\", secondary: \"#FA75BD\")");
swift.push("            static let lime = (primary: \"#99DB54\", secondary: \"#59EDC7\")");
swift.push("            static let slate = (primary: \"#94A6C2\", secondary: \"#566D8F\")");
swift.push("        }");
swift.push("    }");
swift.push("    enum Metrics {");
for (const [name, value] of Object.entries(tokens.radius)) swift.push(`        static let radius${cap(name)}: CGFloat = ${value}`);
for (const [name, value] of Object.entries(tokens.space)) swift.push(`        static let space${cap(name)}: CGFloat = ${value}`);
for (const [name, value] of Object.entries(tokens.type)) swift.push(`        static let type${cap(name)}: CGFloat = ${value}`);
for (const [name, value] of Object.entries(tokens.size)) swift.push(`        static let ${name}: CGFloat = ${value}`);
swift.push("    }");
swift.push("    enum Motion {");
swift.push(`        static let fast = ${parseFloat(tokens.motion.fast) / 1000}`);
swift.push(`        static let snappy = ${parseFloat(tokens.motion.snappy) / 1000}`);
swift.push("    }");
swift.push("}");

writeFileSync(join(root, "Sources/EnvBoxUI/Theme/DesignTokens.swift"), swift.join("\n") + "\n");
console.log("tokens.css + DesignTokens.swift updated");

function kebab(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}
function cap(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}
