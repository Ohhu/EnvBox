import Foundation
import Testing
@testable import EnvBoxCore

@Suite("Active environment")
struct ActiveEnvironmentTests {
    private func makeStore(fileContents: String) throws -> (ActiveEnvironmentStore, URL) {
        let home = try makeTemporaryDirectory()
        let directory = home.appendingPathComponent(".envbox", isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let url = directory.appendingPathComponent("active.zsh")
        try fileContents.write(to: url, atomically: true, encoding: .utf8)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        return (ActiveEnvironmentStore(url: url), home)
    }

    @Test func parsesExportsUnsetsAndGeneration() {
        let content = """
        # Generated by EnvBox. Do not edit this file.
        # Generation: 2026-10-31T20:10:12.345Z-ab12
        # Profile: 本地开发
        # This file contains plaintext values because a shell must read them.
        unset GONE
        export API_TOKEN='secret'
        export QUOTED='it'\\''s fine'
        export EMPTY=''
        """
        let parsed = ActiveEnvironmentStore.parse(content)
        #expect(parsed.generation == "2026-10-31T20:10:12.345Z-ab12")
        #expect(parsed.profileName == "本地开发")
        #expect(parsed.removed == ["GONE"])
        #expect(parsed.values.map(\.key) == ["API_TOKEN", "QUOTED", "EMPTY"])
        #expect(parsed.values[1].value == "it's fine")
        #expect(parsed.values[2].value.isEmpty)
    }

    @Test func unescapeRejectsMalformedValues() {
        #expect(ActiveEnvironmentStore.unescapeSingleQuoted("'plain'") == "plain")
        #expect(ActiveEnvironmentStore.unescapeSingleQuoted("'a'\\''b'") == "a'b")
        #expect(ActiveEnvironmentStore.unescapeSingleQuoted("\"double\"") == nil)
        #expect(ActiveEnvironmentStore.unescapeSingleQuoted("'unterminated") == nil)
    }

    @Test func snapshotNeverExposesValues() throws {
        let (store, home) = try makeStore(fileContents: """
        # Generation: gen-1
        export BAIDU_COOKIES='0123456789'
        """)
        defer { try? FileManager.default.removeItem(at: home) }
        let snapshot = store.snapshot()
        #expect(snapshot.isAvailable)
        #expect(snapshot.generation == "gen-1")
        #expect(snapshot.entries.count == 1)
        #expect(snapshot.entries[0].name == "BAIDU_COOKIES")
        #expect(snapshot.entries[0].length == 10)
        #expect(snapshot.entries[0].fingerprint.count == 8)
        #expect(store.value(forKey: "BAIDU_COOKIES") == "0123456789")
    }

    @Test func missingFileIsUnavailable() throws {
        let home = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: home) }
        let store = ActiveEnvironmentStore(url: home.appendingPathComponent("absent.zsh"))
        #expect(!store.snapshot().isAvailable)
        #expect(store.value(forKey: "ANY") == nil)
    }

    @Test func executeExpandsValuesInsideTheChildProcess() async throws {
        let (store, home) = try makeStore(fileContents: """
        # Generation: gen-2
        export DEMO_TOKEN='abc123'
        """)
        defer { try? FileManager.default.removeItem(at: home) }
        let result = try await store.execute(command: "printf '%s' \"$DEMO_TOKEN\"", requiredKeys: ["DEMO_TOKEN"])
        #expect(result.exitCode == 0)
        #expect(String(decoding: result.stdout, as: UTF8.self) == "abc123")
        #expect(result.generation == "gen-2")
    }

    @Test func executeRejectsMissingRequiredKeys() async throws {
        let (store, home) = try makeStore(fileContents: "# Generation: gen-3\nexport PRESENT='1'\n")
        defer { try? FileManager.default.removeItem(at: home) }
        await #expect(throws: EnvBoxError.self) {
            _ = try await store.execute(command: "true", requiredKeys: ["ABSENT"])
        }
    }

    @Test func executeTimesOut() async throws {
        let (store, home) = try makeStore(fileContents: "# Generation: gen-4\nexport X='1'\n")
        defer { try? FileManager.default.removeItem(at: home) }
        let result = try await store.execute(command: "sleep 5", timeout: 0.5)
        #expect(result.timedOut)
        #expect(result.exitCode != 0)
    }

    @Test func generationChangesOnEveryWrite() async throws {
        let home = try makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: home) }
        let service = ShellIntegrationService(homeDirectory: home, environment: ["SHELL": "/bin/zsh"])
        let profile = sampleProfile()
        let first = try await service.writeActivationScript(profile: profile, staleKeys: [])
        let firstGeneration = ActiveEnvironmentStore(url: first).snapshot().generation
        let second = try await service.writeActivationScript(profile: profile, staleKeys: [])
        let secondGeneration = ActiveEnvironmentStore(url: second).snapshot().generation
        #expect(firstGeneration != nil)
        #expect(firstGeneration != secondGeneration)
    }
}
